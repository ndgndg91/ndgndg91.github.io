export const getStoredCars = (): Car[] => {
  const stored = localStorage.getItem('user_cars');
  if (!stored) {
    localStorage.setItem('user_cars', JSON.stringify(INITIAL_CARS));
    return INITIAL_CARS;
  }
  try {
    const cars = JSON.parse(stored) as Car[];
    // Reset if brand is not Toyota/Lexus, missing new models, or custom URL is missing
    const hasLegacyData = cars.some(car => !car.isCustom && car.brand !== 'Toyota' && car.brand !== 'Lexus');
    const hasNewLexus = cars.some(car => car.id === 'lexus-ls500h');
    const hasRzData = cars.some(car => car.id === 'lexus-rz450e');
    const missingUrlField = cars.some(car => !car.isCustom && !car.officialUrl);
    // 추가검증: size가 한글로 들어간 legacy 데이터가 있으면 리셋
    const hasKoreanSize = cars.some(car => !car.isCustom && car.size.includes('형'));
    if (hasLegacyData || !hasNewLexus || hasRzData || missingUrlField || hasKoreanSize) {
      localStorage.setItem('user_cars', JSON.stringify(INITIAL_CARS));
      return INITIAL_CARS;
    }
    return cars;
  } catch (e) {
    return INITIAL_CARS;
  }
};

export const saveCars = (cars: Car[]) => {
  localStorage.setItem('user_cars', JSON.stringify(cars));
};
